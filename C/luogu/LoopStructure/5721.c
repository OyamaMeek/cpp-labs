// 题目描述
// 给出 n，请输出一个直角边长度是 n 的数字直角三角形。
// 所有数字都是 2 位组成的，如果没有 2 位则加上前导 0。
// 输入格式
// 输入一个正整数 n。
// 输出格式
// 输出如题目要求的数字直角三角形。
// 输入输出样例
// 输入 #1
// 5
// 输出 #1
// 0102030405
// 06070809
// 101112
// 1314
// 15
// 数据保证，1≤n≤13。
#include <stdio.h>
int main ()
{
    int n, num = 1;
    scanf("%d",&n);
    for(int i=1;i<=n;i++)
    {
        for(int j=1;j<=n-i+1;j++)
        {
            printf("%02d",num++);
        }
        printf("\n");
    }
    return 0;
}
